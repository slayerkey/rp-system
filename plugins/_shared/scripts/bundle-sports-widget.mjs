/**
 * Compiles the tracker's portable data layer into the sports widget's source tree.
 *
 * Lives here rather than under widgets/ because esbuild is installed in this package only, and
 * Node resolves it by walking up from this script's own directory.
 */
import esbuild from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, "../../..");
const OUT = path.join(REPO, "widgets/_src/sports/lib/sports-data.js");

await esbuild.build({
	entryPoints: [path.join(HERE, "widget-sports-entry.ts")],
	bundle: true,
	// Classic script, never a module: widgets/_build/inline.py refuses type="module" because an
	// inlined module gets its own scope and iCUE's injected globals stop resolving.
	format: "iife",
	globalName: "SportsData",
	target: "es2017",
	platform: "browser",
	legalComments: "none",
	outfile: OUT,
	banner: {
		js: "/* GENERATED by plugins/_shared/scripts/bundle-sports-widget.mjs from plugins/_shared/src\n   and plugins/ultimate-sports/src. Do not edit; rerun the script instead. */"
	}
});

console.log("bundled -> " + path.relative(REPO, OUT).split(path.sep).join("/"));
